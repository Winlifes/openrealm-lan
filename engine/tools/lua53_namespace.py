#!/usr/bin/env python3
"""Generate checked-in symbol isolation from a plain Lua/Eris static archive."""
import argparse
from pathlib import Path
import re
import subprocess
import sys

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('archive', type=Path)
parser.add_argument('output', type=Path)
parser.add_argument('--check', action='store_true', help='check the isolated archive without rewriting the header')
args = parser.parse_args()
flags = ['-gU'] if sys.platform == 'darwin' else ['-g', '--defined-only']
listing = subprocess.check_output(['nm', *flags, str(args.archive)], text=True)
symbols = set()
unisolated = []
for line in listing.splitlines():
    fields = line.split()
    if not fields:
        continue
    name = fields[-1]
    if sys.platform == 'darwin' and name.startswith('_'):
        name = name[1:]
    if args.check and name.startswith('bz53_'):
        symbols.add(name[len('bz53_'):])
        continue
    if re.fullmatch(r'(?:lua|eris)[A-Za-z0-9_]*', name):
        if args.check:
            unisolated.append(name)
        symbols.add(name)
assert not unisolated, f'Unisolated runtime symbols: {unisolated}'
assert len(symbols) > 200 and 'lua_newstate' in symbols and 'eris_persist' in symbols
lines = ['/* Generated by tools/lua53_namespace.py from the pinned Lua 5.3.4/Eris archive.',
         ' * Public and private symbols must coexist with the independent Lua 5.4 UI runtime. */',
         '#ifndef BZ_LUA53_NAMESPACE_H', '#define BZ_LUA53_NAMESPACE_H', '']
lines.extend(f'#define {name} bz53_{name}' for name in sorted(symbols))
lines.extend(['', '#endif', ''])
content = '\n'.join(lines)
if args.check:
    assert args.output.read_text() == content, 'Runtime exports changed; regenerate the namespace header'
    print(f'Lua 5.3 namespace: {len(symbols)} symbols isolated')
else:
    args.output.write_text(content)
    print(f'Isolated {len(symbols)} Lua/Eris symbols in {args.output}')
